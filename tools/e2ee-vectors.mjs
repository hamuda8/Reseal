#!/usr/bin/env node
// Test vectors for the Zig port of Reseal's end-to-end encryption (src/client/crypto.zig), made by
// the original web client's crypto.js (Reseal-js/public/js/crypto.js) with Node's WebCrypto.
//
//   node tools/e2ee-vectors.mjs [path/to/crypto.js]   (Node 22, no packages)
//
// Writes src/client/testdata/e2ee_vectors.json. The Zig tests open everything in it: identities
// exported as PKCS#8, a chat key wrapped for B, messages (v1 and v2 envelopes), a draft, the three
// key backups, a safety number and an encrypted file. tools/e2ee-verify.mjs checks the other
// direction (what the Zig code makes, crypto.js opens).

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const cryptoPath = path.resolve(process.argv[2] || path.join(here, '../../Reseal-js/public/js/crypto.js'));
const C = await import(pathToFileURL(cryptoPath).href);
const subtle = globalThis.crypto.subtle;
const te = new TextEncoder();

const chatId = '65f1a2b3c4d5e6f708192a3b';
const aliceId = '65f1a2b3c4d5e6f708192a01';
const bobId = '65f1a2b3c4d5e6f708192a02';

// Identities (the escrow backup also hands back the exported bundle: PKCS#8 + raw public keys).
const alice = await C.generateIdentity();
const bob = await C.generateIdentity();
const aliceEscrow = await C.escrowBackup(alice);
const bobEscrow = await C.escrowBackup(bob);

// A chat key, wrapped by Alice for Bob.
const raw = C.newChatKeyBytes();
const wrap = await C.wrapChatKey(raw, { chatId, epoch: 3, userId: bobId, recipientEnc: bob.encPublic, signer: alice.sigPrivate });
const chatKey = await C.importChatKey(raw);

// Messages: the current (v2, per-message key) envelope, Unicode and a long one that needs 2 pad blocks.
const payloads = [
  { v: 1, t: 'Hello Bob 👋 — مرحبا' },
  { v: 1, t: 'x'.repeat(300), ent: [{ t: 'bold', o: 0, l: 3 }] },
];
const messages = [];
for (const p of payloads) messages.push({ payload: p, env: await C.encryptMessage(chatKey, p, { chatId, epoch: 3, senderId: aliceId, signer: alice.sigPrivate }) });

// A v1 envelope (before per-message keys): the chat key itself, no salt. Made as the old client did.
function pad(bytes, block = 128) {
  const out = new Uint8Array(Math.ceil((bytes.length + 1) / block) * block);
  out.set(bytes);
  out[bytes.length] = 0x80;
  return out;
}
const v1Payload = { v: 1, t: 'an old message' };
const v1Iv = C.random(12);
const v1Ct = await subtle.encrypt({ name: 'AES-GCM', iv: v1Iv, additionalData: te.encode(`reseal/msg/v1|${chatId}|3|${aliceId}`) }, chatKey, pad(te.encode(JSON.stringify(v1Payload))));
const v1Env = { e: 3, iv: C.toB64(v1Iv), ct: C.toB64(v1Ct) };
v1Env.sig = await C.sign(alice.sigPrivate, `reseal/msgsig/v1|${chatId}|3|${aliceId}|${v1Env.iv}|${v1Env.ct}`);
messages.push({ payload: v1Payload, env: v1Env });

// Draft, backups.
const draft = await C.encryptDraft(chatKey, 3, { t: 'unsent words' }, chatId);
const passcode = 'correct horse 42';
const passcodeBox = await C.passcodeBackup(aliceEscrow.bundle, passcode, 2000);
const recovery = await C.recoveryBackup(aliceEscrow.bundle);

// Safety number and fingerprint.
const safety = await C.safetyNumber({ enc: alice.encPublic, sig: alice.sigPublic }, { enc: bob.encPublic, sig: bob.sigPublic });
const fp = Array.from(await C.fingerprint(alice.encPublic, alice.sigPublic), b => b.toString(16).padStart(2, '0')).join('');

// A file in two chunks.
const fk = await C.newFileKey();
const chunk0 = C.utf8('first chunk of the file, ');
const chunk1 = C.utf8('and the last one.');
const file = {
  key: fk.keyB64, iv: fk.ivB64,
  chunks: [C.toB64(await C.encryptChunk(fk.key, fk.iv, 0, false, chunk0)), C.toB64(await C.encryptChunk(fk.key, fk.iv, 1, true, chunk1))],
  plain: 'first chunk of the file, and the last one.',
  sha256: await C.sha256Hex(C.utf8('first chunk of the file, and the last one.')),
};

const out = {
  note: 'Generated by tools/e2ee-vectors.mjs from Reseal-js crypto.js. Do not edit.',
  chatId, aliceId, bobId,
  alice: aliceEscrow.bundle,
  bob: bobEscrow.bundle,
  chatKey: C.toB64(raw),
  wrap: { ...wrap, epoch: 3 },
  messages,
  draft: { env: draft, payload: { t: 'unsent words' } },
  passcode, passcodeBox,
  recovery: { box: recovery.backup, key: recovery.recoveryKey },
  escrow: { box: aliceEscrow.box, key: aliceEscrow.escrowKey },
  safety, fingerprint: fp,
  file,
  b64: { bytes: C.toB64(Uint8Array.from([0, 1, 2, 250, 251, 252, 253, 254, 255])), urlsafe: '-_8', urlsafeBytes: [251, 255] },
};
const dest = path.join(here, '../src/client/testdata/e2ee_vectors.json');
fs.writeFileSync(dest, JSON.stringify(out, null, 2) + '\n');
console.log('wrote', path.relative(process.cwd(), dest));
