#!/usr/bin/env node
// Reseal-js's emoji set (public/js/data/emoji.js: categories, search keywords, quick reactions,
// emoji stickers) as Zig data: src/client/emoji_data.zig.
//
//   node tools/emoji.mjs [path/to/emoji.js]     (Node 22, no packages)
//
// The emoji are message content people pick; the app's own chrome (tabs, buttons) uses words
// and icons, never emoji.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const src = path.resolve(process.argv[2] || path.join(here, '../../Reseal-js/public/js/data/emoji.js'));
const E = await import(pathToFileURL(src).href);
const text = fs.readFileSync(src, 'utf8');
// KEYWORDS is not exported: read the literal.
const kStart = text.indexOf('const KEYWORDS = {');
const kEnd = text.indexOf('\n};', kStart);
const KEYWORDS = new Function(`return ${text.slice(kStart + 'const KEYWORDS = '.length, kEnd + 3)}`)();

const q = (s) => JSON.stringify(s);
let out = `//! Emoji for messages (picker, reactions, emoji stickers), generated by tools/emoji.mjs from
//! Reseal-js public/js/data/emoji.js. Do not edit.

pub const Category = struct { id: []const u8, name: []const u8, list: []const []const u8 };

pub const categories = [_]Category{
`;
for (const c of E.CATEGORIES) out += `    .{ .id = ${q(c.id)}, .name = ${q(c.name)}, .list = &.{ ${c.list.map(q).join(', ')} } },\n`;
out += `};

pub const Keyword = struct { emoji: []const u8, words: []const u8 };

/// English search words for the common ones.
pub const keywords = [_]Keyword{
${Object.entries(KEYWORDS).map(([e, w]) => `    .{ .emoji = ${q(e)}, .words = ${q(w)} },`).join('\n')}
};

pub const quick_reactions = [_][]const u8{ ${E.QUICK_REACTIONS.map(q).join(', ')} };

/// Big emoji "stickers" (no image files).
pub const stickers = [_][]const u8{ ${E.STICKERS.map(q).join(', ')} };
`;
const dest = path.join(here, '../src/client/emoji_data.zig');
fs.writeFileSync(dest, out);
console.log(`wrote ${E.CATEGORIES.reduce((n, c) => n + c.list.length, 0)} emoji, ${Object.keys(KEYWORDS).length} keywords to ${path.relative(process.cwd(), dest)}`);
